#!/usr/bin/env node
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sdkRelative = 'examples/micro-app-sdk'
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const json = value => JSON.stringify(value, null, 2) + '\n'

export function validateRelease(release) {
  assert.equal(release.schemaVersion, 1, 'Unsupported SDK registry schema')
  assert.match(release.sdkVersion, /^[1-9]\d*\.\d+\.\d+$/)
  assert.equal(release.status, 'REPOSITORY_CANDIDATE', 'Publishing is separate from local SDK generation')
  assert.deepEqual(Object.keys(release.contracts).sort(), ['context','microProps','notification'])
  for (const version of Object.values(release.contracts)) assert.match(version, /^\d+\.\d+$/)
  assert.deepEqual(release.supportedSdkVersions, [release.sdkVersion], 'Register actual releases only')
  for (const value of Object.values(release.limits)) assert(Number.isSafeInteger(value) && value > 0,'Invalid SDK limit')
  assert.equal(release.sdkVersion, '3.0.0', 'Register a new major for the UUID v7-only runtime')
  assert.equal(release.compatibility.previousRelease, '2.0.0')
  assert(!Object.hasOwn(release, 'legacy'), 'Archived runtimes are not active compatibility inputs')
  return release
}

export function protocolArtifacts(release) {
  const names = { SDK_VERSION: release.sdkVersion, CONTEXT_CONTRACT_VERSION: release.contracts.context,
    MICRO_PROPS_CONTRACT_VERSION: release.contracts.microProps,
    NOTIFICATION_CONTRACT_VERSION: release.contracts.notification, DEFAULT_MAX_JSON_RESPONSE_BYTES: release.limits.maxJsonResponseBytes,
    MAX_HTTP_RESPONSE_BYTES: release.limits.maxResponseBytes, MAX_ORGANIZATION_SCOPE_IDS: release.limits.maxOrganizationScopeIds }
  const header = `// Generated by scripts/sync-micro-sdk.mjs from release.json.\n`
  const runtime = header + Object.entries(names).map(([key,value])=>`export const ${key} = ${JSON.stringify(value)}\n`).join('')
    + `export const SUPPORTED_SDK_VERSIONS = Object.freeze(${JSON.stringify(release.supportedSdkVersions)})\n`
    + `export function isSupportedSdkVersion(value) { return typeof value === 'string' && SUPPORTED_SDK_VERSIONS.includes(value) }\n`
    + `export function assertSupportedSdkVersion(value) {\n  if (!isSupportedSdkVersion(value)) { const error = new Error('Unsupported SDK version'); error.code = 'UNSUPPORTED_SDK_VERSION'; throw error }\n}\n`
  const types = header + Object.entries(names).map(([key,value])=>`export declare const ${key}: ${JSON.stringify(value)}\n`).join('')
    + `export declare const SUPPORTED_SDK_VERSIONS: readonly ${JSON.stringify(release.sdkVersion)}[]\n`
    + `export declare function isSupportedSdkVersion(value: unknown): value is ${JSON.stringify(release.sdkVersion)}\n`
    + `export declare function assertSupportedSdkVersion(value: unknown): asserts value is ${JSON.stringify(release.sdkVersion)}\n`
  return new Map([[`${sdkRelative}/generated/protocol.mjs`,runtime],[`${sdkRelative}/generated/protocol.d.mts`,types]])
}

function assertSafeDestination(root, relative) {
  assert(!path.isAbsolute(relative) && !relative.split('/').includes('..'), 'Unsafe SDK output')
  let current = root
  for (const part of relative.split('/')) {
    current = path.join(current,part)
    if (existsSync(current)) assert(!lstatSync(current).isSymbolicLink(), 'SDK generation refuses symlinks')
  }
  return current
}

export async function generateArtifacts({ root = repository } = {}) {
  const sdkRoot = path.join(root,sdkRelative)
  const release = validateRelease(JSON.parse(readFileSync(path.join(sdkRoot,'release.json'),'utf8')))
  const artifacts = protocolArtifacts(release)
  const { generateContractArtifacts } = await import(pathToFileURL(path.join(sdkRoot,'scripts/generate-contracts.mjs')).href)
  for (const [file,content] of generateContractArtifacts({ root, sdkRoot, release })) artifacts.set(file,content)
  const require = createRequire(path.join(repository,'package.json'))
  // Protocol imports must resolve without overwriting checked files during --check.
  const plugin = { name:'sdk-canonical-protocol', setup(build) {
    build.onResolve({ filter:/generated[\\/]protocol\.mjs$/ }, () => ({ path:'sdk-protocol',namespace:'canonical-sdk' }))
    build.onLoad({ filter:/.*/,namespace:'canonical-sdk' }, () => ({ contents: artifacts.get(`${sdkRelative}/generated/protocol.mjs`), loader:'js' }))
  } }
  // The async build API supports a canonical virtual protocol module; see below.
  const { build } = require('esbuild')
  const compile = async (entry,format) => (await build({ absWorkingDir:root,entryPoints:[`${sdkRelative}/src/${entry}`],
    nodePaths:[path.join(repository,'node_modules')],bundle:true,format,platform:'browser',target:'es2022',write:false,charset:'utf8',legalComments:'inline',plugins:[plugin],
    banner:{js:`/* Generated SaaS Micro SDK ${release.sdkVersion}; source: ${sdkRelative}/release.json */`},logLevel:'silent' })).outputFiles[0].text
  const classic = await compile('classic-entry.mjs','iife'), esm = await compile('index.mjs','esm')
  const base = `${sdkRelative}/releases/${release.sdkVersion}`
  const packageInfo = {name:'@saas-platform/micro-app-sdk',version:release.sdkVersion,private:true,type:'module',
    exports:{'.':{types:'./index.d.mts',import:'./index.mjs'},'./sdk.js':'./sdk.js','./schema.json':'./schema.json','./protocol.rs':'./protocol.rs'}}
  artifacts.set(`${base}/package.json`,json(packageInfo))
  artifacts.set(`${base}/index.mjs`,esm)
  artifacts.set(`${base}/sdk.js`,classic)
  artifacts.set(`${base}/types.d.ts`,artifacts.get(`${sdkRelative}/generated/types.d.ts`))
  artifacts.set(`${base}/schema.json`,artifacts.get(`${sdkRelative}/generated/schema.json`))
  artifacts.set(`${base}/protocol.rs`,artifacts.get(`${sdkRelative}/generated/protocol.rs`))
  const declarations = readFileSync(path.join(sdkRoot,'src/index.d.mts'),'utf8')
    .replaceAll('../generated/types.js','./types.js').replaceAll('../generated/types.d.ts','./types.js')
    .replaceAll('../generated/protocol.mjs','./protocol.mjs').replaceAll('./http.mjs','./http.mjs')
  artifacts.set(`${base}/index.d.mts`,declarations)
  artifacts.set(`${base}/index.d.ts`,declarations)
  artifacts.set(`${base}/http.d.mts`,readFileSync(path.join(sdkRoot,'src/http.d.mts'),'utf8').replaceAll('../generated/types.js','./types.js'))
  artifacts.set(`${base}/protocol.mjs`,artifacts.get(`${sdkRelative}/generated/protocol.mjs`))
  artifacts.set(`${base}/protocol.d.mts`,artifacts.get(`${sdkRelative}/generated/protocol.d.mts`))
  if (existsSync(path.join(sdkRoot,'src/capabilities.d.mts'))) artifacts.set(`${base}/capabilities.d.mts`,readFileSync(path.join(sdkRoot,'src/capabilities.d.mts'),'utf8'))
  artifacts.set(`${sdkRelative}/package.json`,json({...packageInfo,exports:{'.':{types:'./index.d.mts',import:'./index.mjs'},'./sdk.js':`./releases/${release.sdkVersion}/sdk.js`,'./schema.json':`./releases/${release.sdkVersion}/schema.json`,'./protocol.rs':`./releases/${release.sdkVersion}/protocol.rs`}}))
  artifacts.set(`${sdkRelative}/index.mjs`,`// Generated package entry for registered SDK ${release.sdkVersion}.\nexport * from './releases/${release.sdkVersion}/index.mjs'\n`)
  artifacts.set(`${sdkRelative}/index.d.mts`,`export * from './releases/${release.sdkVersion}/index.mjs'\n`)
  const entries = [...artifacts].filter(([file])=>file.startsWith(base+'/')).map(([file,content])=>({path:file.slice(base.length+1),bytes:Buffer.byteLength(content),sha256:hash(content)})).sort((a,b)=>a.path.localeCompare(b.path,'en'))
  artifacts.set(`${base}/artifact-manifest.json`,json({schemaVersion:1,sdkVersion:release.sdkVersion,contracts:release.contracts,files:entries}))
  return { release, artifacts }
}

export async function syncSdk({ root = repository, check = false, scope = 'all' } = {}) {
  assert(['all','sdk'].includes(scope),'Unknown SDK generation scope')
  const { release, artifacts } = await generateArtifacts({root})
  const selected = [...artifacts]
  const mismatches = []
  const base = `${sdkRelative}/releases/${release.sdkVersion}`
  const expected = new Set(selected.filter(([file])=>file.startsWith(base+'/')).map(([file])=>file))
  const unexpected = []
  function inspect(relative) {
    const absolute=assertSafeDestination(root,relative)
    if (!existsSync(absolute)) return
    const info=lstatSync(absolute)
    if(info.isDirectory())for(const name of readdirSync(absolute).sort())inspect(`${relative}/${name}`)
    else if(!info.isFile()||!expected.has(relative))unexpected.push(relative)
  }
  inspect(base)
  if(unexpected.length)throw new Error(`Unregistered files in SDK release: ${unexpected.join(', ')}`)
  for (const [file,content] of selected) {
    assert.equal(typeof content,'string',`Missing generated artifact ${file}`)
    const target = assertSafeDestination(root,file)
    if (check) { if (!existsSync(target)||!readFileSync(target).equals(Buffer.from(content))) mismatches.push(file) }
    else { mkdirSync(path.dirname(target),{recursive:true});writeFileSync(target,content) }
  }
  if (mismatches.length) throw new Error(`SDK artifact drift: ${mismatches.join(', ')}; run npm run sdk:sync and review the changes`)
  return { status:'PASS',mode:check?'CHECK':'WRITE',scope,sdkVersion:release.sdkVersion,artifactCount:selected.length }
}

